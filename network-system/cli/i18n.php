<?php
declare(strict_types=1);

/*
 * أدوات الترجمة:
 *   php cli/i18n.php js       يولّد نسخ JavaScript الإنجليزية في public/assets/js/i18n/en من الملفات الأصلية والقاموس
 *   php cli/i18n.php check    يتحقق أن النسخ الإنجليزية محدّثة (للبناء)، ويخرج برمز 1 إن لم تكن
 */

if (PHP_SAPI !== 'cli') {
    exit(1);
}

require dirname(__DIR__) . '/app/bootstrap.php';

use App\Core\I18n;
use App\Core\Lang;

$cmd = $argv[1] ?? '';
$src = PUBLIC_PATH . '/assets/js';
$dst = $src . '/i18n/en';
Lang::set('en');

$build = static function () use ($src): array {
    $out = [];
    foreach (glob($src . '/*.js') ?: [] as $file) {
        $code = (string) file_get_contents($file);
        $out[basename($file)] = "/* English build of " . basename($file) . " — generated by cli/i18n.php, do not edit */\n" . I18n::text($code);
    }
    return $out;
};

if ($cmd === 'js') {
    if (!is_dir($dst) && !mkdir($dst, 0755, true) && !is_dir($dst)) {
        fwrite(STDERR, "cannot create $dst\n");
        exit(1);
    }
    foreach (glob($dst . '/*.js') ?: [] as $old) {
        unlink($old);
    }
    $n = 0;
    foreach ($build() as $name => $code) {
        file_put_contents($dst . '/' . $name, $code);
        $n++;
    }
    echo "generated $n files in public/assets/js/i18n/en\n";
    exit(0);
}

if ($cmd === 'check') {
    $stale = [];
    foreach ($build() as $name => $code) {
        $f = $dst . '/' . $name;
        if (!is_file($f) || file_get_contents($f) !== $code) {
            $stale[] = $name;
        }
    }
    if ($stale) {
        fwrite(STDERR, "outdated English JS: " . implode(', ', $stale) . "\nrun: php cli/i18n.php js\n");
        exit(1);
    }
    echo "English JS is up to date\n";
    exit(0);
}

fwrite(STDERR, "usage: php cli/i18n.php js|check\n");
exit(1);
