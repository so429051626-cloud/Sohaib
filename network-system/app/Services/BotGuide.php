            'بعض الصفحات لا تظهر إلا لمن لديه صلاحيتها، أو إن كانت ضمن باقة اشتراكه في المنصة.',
        ];
        foreach (self::MENU as $group => $pages) {
            $lines[] = $group . ':';
            foreach ($pages as [$name, $path, $what]) {
                $lines[] = '- ' . $name . ' (' . $path . '): ' . $what;
            }
        }
        return implode("\n", $lines);
    }
