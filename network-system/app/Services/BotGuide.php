    public static function text(): string
    {
        $lines = [
            'دليل نظام صاحب الشبكة: الصفحات كما تظهر في قائمته الجانبية، ورابط كل صفحة يُكتب بعد رابط حسابه (مثلاً رابط المنصة/اسم-الحساب/routers).',
